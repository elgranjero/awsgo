package cmd

import (
	"context"

	"github.com/aws/aws-sdk-go-v2/aws"
	"github.com/aws/aws-sdk-go-v2/service/forecastquery"
	log "github.com/sirupsen/logrus"
	"github.com/spf13/cobra"
)

// forecastqueryCmd represents the forecastquery command
var _forecastqueryCmd = &cobra.Command{
	Use:   "forecastquery",
	Short: "AWS forecastquery CLI",
	Run: func(cmd *cobra.Command, args []string) {
		cfg, err := LoadAWSConfigWithMiddleware(_awsProfile)
		if err != nil {
			log.Errorf("Failed to load configuration: %s", err.Error())
			return
		}
		if len(_awsRegion) > 0 {
			cfg.Region = _awsRegion
		}
		client := forecastquery.NewFromConfig(cfg)
		if _forecastqueryQueryForecast {
			forecastquery_QueryForecast(cfg, client)
			return
		}
		if _forecastqueryQueryWhatIfForecast {
			forecastquery_QueryWhatIfForecast(cfg, client)
			return
		}

	},
}

var (
	_forecastqueryQueryForecast       bool
	_forecastqueryQueryWhatIfForecast bool

	_forecastqueryEndDate           string
	_forecastqueryFilters           string
	_forecastqueryForecastArn       string
	_forecastqueryNextToken         string
	_forecastqueryStartDate         string
	_forecastqueryWhatIfForecastArn string
)

// Retrieves a forecast for a single item, filtered by the supplied criteria.
// The criteria is a key-value pair. The key is either item_id (or the equivalent
// non-timestamp, non-target field) from the TARGET_TIME_SERIES dataset, or one of
// the forecast dimensions specified as part of the FeaturizationConfig object.
//
// By default, QueryForecast returns the complete date range for the filtered
// forecast. You can request a specific date range.
//
// To get the full forecast, use the [CreateForecastExportJob] operation.
//
// The forecasts generated by Amazon Forecast are in the same timezone as the
// dataset that was used to create the predictor.
//
// [CreateForecastExportJob]: https://docs.aws.amazon.com/en_us/forecast/latest/dg/API_CreateForecastExportJob.html
func forecastquery_QueryForecast(cfg aws.Config, client *forecastquery.Client) {
	input := &forecastquery.QueryForecastInput{
		// Filters: map[string]string, // Required
		// ForecastArn: *string, // Required
	}

	if len(_forecastqueryFilters) > 0 {
		if err := assignInputField(input, "Filters", _forecastqueryFilters); err != nil {
			log.Errorf("invalid --filters: %s", err.Error())
			return
		}
	}
	if len(_forecastqueryForecastArn) > 0 {
		input.ForecastArn = aws.String(_forecastqueryForecastArn)
	}
	if len(_forecastqueryEndDate) > 0 {
		input.EndDate = aws.String(_forecastqueryEndDate)
	}
	if len(_forecastqueryNextToken) > 0 {
		input.NextToken = aws.String(_forecastqueryNextToken)
	}
	if len(_forecastqueryStartDate) > 0 {
		input.StartDate = aws.String(_forecastqueryStartDate)
	}

	if resp, err := client.QueryForecast(context.TODO(), input); err != nil {
		log.Errorf("%s", err.Error())
		return
	} else {
		writeOutput(nil, nil, resp, _awsOutput)
	}
}

